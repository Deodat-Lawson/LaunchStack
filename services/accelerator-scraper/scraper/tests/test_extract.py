"""HTML fixtures for the extractors. No network."""

import unittest
from datetime import date, datetime, timezone
from pathlib import Path

from scraper.facts import Findings, classify, same_site
from scraper.parse import Page
from scraper.records import narrative_from, skeleton

FIXTURES = Path(__file__).parent / "fixtures"
RECORD = skeleton(
    "acme-labs",
    "Acme Labs",
    "https://acme.example/",
    "https://acme.example/apply",
    datetime(2026, 11, 9, tzinfo=timezone.utc),
)
TODAY = date(2026, 11, 9)


def read(name: str, url: str = "https://acme.example/program") -> Findings:
    html = (FIXTURES / name).read_text()
    findings = Findings(RECORD, TODAY)
    findings.read(url, "terms", Page.read(url, html))
    return findings


def values(findings: Findings, key: str) -> list:
    return [item["value"] for item in findings.found[key]]


class DealTerms(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.findings = read("deal-terms.html")

    def test_safe_grant_convertible_and_fee_are_separate(self) -> None:
        kinds = [item["kind"] for item in values(self.findings, "dealComponents")]
        self.assertIn("safe", kinds)
        self.assertIn("grant", kinds)
        self.assertIn("convertible", kinds)
        self.assertIn("fee", kinds)
        safe = next(item for item in values(self.findings, "dealComponents") if item["kind"] == "safe")
        self.assertEqual(safe["amount"], "150000")
        self.assertEqual(safe["currency"], "USD")
        grant = next(item for item in values(self.findings, "dealComponents") if item["kind"] == "grant")
        self.assertEqual(grant["amount"], "20000")
        self.assertEqual(grant["currency"], "EUR")
        note = next(item for item in values(self.findings, "dealComponents") if item["kind"] == "convertible")
        self.assertEqual(note["amount"], "50000")
        self.assertEqual(note["currency"], "GBP")
        self.assertTrue(note["contingent"])
        fee = next(item for item in values(self.findings, "dealComponents") if item["kind"] == "fee" and item["amount"] == "5000")
        self.assertEqual(fee["currency"], "USD")
        self.assertTrue(any(item["amount"] == "0" and item["kind"] == "fee" for item in values(self.findings, "dealComponents")))

    def test_portfolio_news_is_not_an_offer(self) -> None:
        self.assertFalse(any(item["amount"] == "40000000" for item in values(self.findings, "dealComponents")))

    def test_every_component_cites_an_excerpt(self) -> None:
        for item in self.findings.found["dealComponents"]:
            excerpt = self.findings.evidence[item["evidenceId"]]["excerpt"]
            self.assertTrue(excerpt)
            self.assertNotIn("Series B", excerpt)


