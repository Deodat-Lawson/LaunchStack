"""Program records on disk: loading, recognising homepage records, and writing without churn."""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

from . import PROGRAMS, iso

ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
FORM_LIMITATIONS = [
    "This pass retrieved the public page and did not open an application. No account was created, no terms were accepted, and nothing was submitted. Fields stay empty and Start Application stays blocked.",
    "No deadline, clock, or timezone was confirmed in this pass, so deadlineAt and dateOnly stay empty.",
]


def dump(record: object) -> str:
    return json.dumps(record, indent=2, ensure_ascii=False) + "\n"


def write_if_changed(path: Path, record: dict, ignore: tuple[str, ...] = ("checkedAt",)) -> bool:
    """Write only when something other than the ignored fields changed, so git stays quiet."""
    if path.exists():
        previous = json.loads(path.read_text())
        if {**previous, **dict.fromkeys(ignore)} == {**record, **dict.fromkeys(ignore)}:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(record))
    return True


def program_ids(requested: list[str] | None = None) -> list[str]:
    if requested:
        missing = [program_id for program_id in requested if not (PROGRAMS / f"{program_id}.json").exists()]
        if missing:
            raise SystemExit(f"No Program file for: {', '.join(missing)}")
        return list(requested)
    ids = sorted(path.stem for path in PROGRAMS.glob("*.json"))
    if not ids:
        raise SystemExit(f"No Program files in {PROGRAMS}")
    return ids


def load_program(program_id: str) -> dict:
    path = PROGRAMS / f"{program_id}.json"
    program = json.loads(path.read_text())
    if program.get("id") != program_id:
        raise SystemExit(f"{path} id does not match the filename")
    return program


def is_homepage_record(program: dict) -> bool:
    """Records this tool owns: one homepage quote, one logo source, one empty public-page cycle."""
    ids = sorted(source["id"] for source in program["sources"])
    cycles = program["cycles"]
    return (
        ids == ["homepage", "official-logo"]
        and len(cycles) == 1
        and cycles[0]["id"] == "public-page"
        and not cycles[0].get("form", {}).get("fields")
    )


def narratives(quote: str, now: datetime) -> tuple[dict, dict]:
    day = now.strftime("%Y-%m-%d")
    description = {
        "text": (
            f"Generated by fixtures/accelerators/scrape.py from the official page retrieved on {day}. "
            f"It repeats that page's visible text and adds nothing to it: {quote} "
            "No application form was opened, and this record does not add a deadline, "
            "investment instrument, or eligibility rule beyond that quoted text."
        ),
        "sourceIds": ["homepage"],
        "interpretation": True,
    }
    target = {
        "text": (
            "Generated by fixtures/accelerators/scrape.py from the same official page: who the program "
            "addresses is only what that page says in the quoted text. This is not a closed stage list "
            "or an eligibility rule. The application questions were not reviewed."
        ),
        "sourceIds": ["homepage"],
        "interpretation": True,
    }
    return description, target


