"""Program records on disk: loading, recognising homepage records, and writing without churn."""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

from . import PROGRAMS, iso

ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")


def dump(record: object) -> str:
    return json.dumps(record, indent=2, ensure_ascii=False) + "\n"


def _without(value: object, ignore: tuple[str, ...]) -> object:
    """Drop timestamp fields at every level so a warm rerun does not rewrite files."""
    if isinstance(value, dict):
        return {key: _without(item, ignore) for key, item in value.items() if key not in ignore}
    if isinstance(value, list):
        return [_without(item, ignore) for item in value]
    return value


def write_if_changed(path: Path, record: dict, ignore: tuple[str, ...] = ("checkedAt", "lastAttemptAt", "lastSuccessAt", "harvestedAt")) -> bool:
    """Write only when something other than the ignored fields changed, so git stays quiet."""
    if path.exists() and _without(json.loads(path.read_text()), ignore) == _without(record, ignore):
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump(record))
    return True


def program_ids(requested: list[str] | None = None) -> list[str]:
    if requested:
        missing = [program_id for program_id in requested if not (PROGRAMS / f"{program_id}.json").exists()]
        if missing:
            raise SystemExit(f"No Program file for: {', '.join(missing)}")
        return list(requested)
    ids = sorted(path.stem for path in PROGRAMS.glob("*.json"))
    if not ids:
        raise SystemExit(f"No Program files in {PROGRAMS}")
    return ids


def load_program(program_id: str) -> dict:
    path = PROGRAMS / f"{program_id}.json"
    program = json.loads(path.read_text())
    if program.get("id") != program_id:
        raise SystemExit(f"{path} id does not match the filename")
    return program


def is_homepage_record(program: dict) -> bool:
    """Records this tool owns: one homepage quote, one logo source, one empty public-page cycle."""
    ids = sorted(source["id"] for source in program["sources"])
    cycles = program["cycles"]
    return (
        ids == ["homepage", "official-logo"]
        and len(cycles) == 1
        and cycles[0]["id"] == "public-page"
        and not cycles[0].get("form", {}).get("fields")
    )


MISSING_NARRATIVE = "Not published on the official page."
_WHO = re.compile(r"\b(?:founders?|start-?ups?|entrepreneurs?|teams?)\b", re.I)


def narrative_from(page: object) -> tuple[dict, dict]:
    """A real description from the meta description or the first substantive paragraphs.

    Navigation, script boilerplate, and browser warnings are not a narrative. When the page
    does not publish one, both fields say so instead of inventing a summary.
    """
    meta = getattr(page, "meta_description", "") or ""
    paragraphs = [item for item in getattr(page, "paragraphs", []) if not _junk_narrative(item)]
    description_text = meta if len(meta) >= 40 and not _junk_narrative(meta) else (paragraphs[0] if paragraphs else "")
    who = next((item for item in paragraphs if _WHO.search(item)), "")
    if not description_text or _junk_narrative(description_text):
        description_text = MISSING_NARRATIVE
    if not who or _junk_narrative(who):
        who = MISSING_NARRATIVE
    return (
        {"text": description_text[:1200], "sourceIds": ["homepage"], "interpretation": True},
        {"text": who[:1200], "sourceIds": ["homepage"], "interpretation": True},
    )


def _junk_narrative(text: str) -> bool:
    lowered = text.lower()
    return (
        "generated by fixtures/accelerators/scrape.py" in lowered
        or "does not add a deadline" in lowered
        or "you are using an unsupported browser" in lowered
        or lowered.startswith("skip to ")
    )


def narratives(quote: str, now: datetime) -> tuple[dict, dict]:
    """Kept for callers that only have a quote. Prefer narrative_from when the page was read."""
    del now
    text = quote.strip()
    if not text or _junk_narrative(text):
        text = MISSING_NARRATIVE
    record = {"text": text[:1200], "sourceIds": ["homepage"], "interpretation": True}
    return record, dict(record)


