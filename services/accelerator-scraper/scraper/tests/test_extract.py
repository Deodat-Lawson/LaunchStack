class Classify(unittest.TestCase):
    def test_collect_samples_stay_stable(self) -> None:
        samples = {
            "https://speedrun.a16z.com/companies": "portfolio",
            "https://speedrun.a16z.com/faq": "terms",
            "https://www.antler.co/cohort-start-dates": "batches",
            "https://www.eranyc.com/apply/": "application",
            "https://skydeck.berkeley.edu/program/": "details",
            "https://example.com/blog/hello": "other",
            "https://a16z.com/terms-of-use/": "other",
            "https://a16z.com/announcement/investing-in-phaze/": "other",
            "https://acme.example/eligibility": "details",
            "https://acme.example/timeline": "batches",
        }
        for url, expected in samples.items():
            self.assertEqual(classify(url, ""), expected, url)

    def test_www_matches_the_apex_host(self) -> None:
        self.assertTrue(same_site("https://awesomeinc.org/fund", ["http://www.awesomeinc.org/"]))
        self.assertFalse(same_site("https://other.example/fund", ["http://www.awesomeinc.org/"]))

    def test_virtual_office_is_not_a_program_format(self) -> None:
        html = "<html><body><p>Rent a virtual office downtown. The program itself is hybrid.</p></body></html>"
        findings = Findings(RECORD, TODAY)
        findings.read("https://acme.example/", "details", Page.read("https://acme.example/", html))
        self.assertEqual(values(findings, "format"), ["hybrid"])


class Vetting(unittest.TestCase):
    def test_accepts_a_cohort_that_invests_and_rejects_a_coworking_space(self) -> None:
        from scraper.discover import vet_text

        decision, reason, signals = vet_text(
            "Our accelerator cohort invests $150k for 7% equity. Apply for the next batch. Demo day is in June."
        )
        self.assertEqual(decision, "accept", reason)
        self.assertIn("cohort", signals)
        decision, reason, _signals = vet_text("A coworking space with desks for rent and community events.")
        self.assertEqual(decision, "reject", reason)
        decision, reason, _signals = vet_text("An incubator that offers office space. No funding is mentioned.")
        self.assertEqual(decision, "reject", reason)
        decision, reason, _signals = vet_text("Undergraduate course. Enroll in the course for credit.")
        self.assertEqual(decision, "reject", reason)

    def test_ordinary_words_are_not_investment_signals(self) -> None:
        from scraper.discover import vet_text

        # The page that let a chamber of commerce through: "safe", "equity" and "application" only.
        decision, reason, signals = vet_text(
            "A safe space for small business. Our equity and inclusion work. Submit an application to join."
        )
        self.assertEqual(decision, "reject", reason)
        self.assertNotIn("investment", signals)
        decision, reason, signals = vet_text("We invest $100k on a SAFE in each accelerator company. Apply now.")
        self.assertEqual(decision, "accept", reason)
        self.assertIn("investment", signals)

    def test_training_programs_and_incubators_without_an_accelerator_are_rejected(self) -> None:
        from scraper.discover import vet_text

        decision, reason, _signals = vet_text(
            "NSF I-Corps hub: a seven-week cohort of customer discovery training. Apply to the next cohort."
        )
        self.assertEqual(decision, "reject", reason)
        decision, reason, _signals = vet_text(
            "Our biotech incubator offers lab space and invests $50k in exchange for 5% equity. Apply today."
        )
        self.assertEqual(decision, "reject", reason)
        decision, reason, _signals = vet_text(
            "The incubator also runs a 12-week accelerator cohort with a demo day. Apply by March 1."
        )
        self.assertEqual(decision, "accept", reason)


